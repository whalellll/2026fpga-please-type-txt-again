package e91c.core
import chisel3._
// Board-compatible AXI wrapper. Legacy observation ports remain tied to zero.
class CoreTop extends RawModule {
  val io = IO(new Bundle {
    val aclk = Input(Clock())
    val aresetn = Input(UInt(1.W))
    val resetVector = Input(UInt(32.W))
    val intrpt = Input(UInt(8.W))
    val arid = Output(UInt(4.W))
    val araddr = Output(UInt(32.W))
    val arlen = Output(UInt(8.W))
    val arsize = Output(UInt(3.W))
    val arburst = Output(UInt(2.W))
    val arlock = Output(UInt(2.W))
    val arcache = Output(UInt(4.W))
    val arprot = Output(UInt(3.W))
    val arvalid = Output(UInt(1.W))
    val arready = Input(UInt(1.W))
    val rid = Input(UInt(4.W))
    val rdata = Input(UInt(32.W))
    val rresp = Input(UInt(2.W))
    val rlast = Input(UInt(1.W))
    val rvalid = Input(UInt(1.W))
    val rready = Output(UInt(1.W))
    val awid = Output(UInt(4.W))
    val awaddr = Output(UInt(32.W))
    val awlen = Output(UInt(8.W))
    val awsize = Output(UInt(3.W))
    val awburst = Output(UInt(2.W))
    val awlock = Output(UInt(2.W))
    val awcache = Output(UInt(4.W))
    val awprot = Output(UInt(3.W))
    val awvalid = Output(UInt(1.W))
    val awready = Input(UInt(1.W))
    val wid = Output(UInt(4.W))
    val wdata = Output(UInt(32.W))
    val wstrb = Output(UInt(4.W))
    val wlast = Output(UInt(1.W))
    val wvalid = Output(UInt(1.W))
    val wready = Input(UInt(1.W))
    val bid = Input(UInt(4.W))
    val bresp = Input(UInt(2.W))
    val bvalid = Input(UInt(1.W))
    val bready = Output(UInt(1.W))
    val fatalMemoryError = Output(Bool())
    val break_point = Input(UInt(1.W))
    val infor_flag = Input(UInt(1.W))
    val reg_num = Input(UInt(5.W))
    val ws_valid = Output(UInt(1.W))
    val rf_rdata = Output(UInt(32.W))
    val debug0_wb_pc = Output(UInt(32.W))
    val debug0_wb_rf_wen = Output(UInt(4.W))
    val debug0_wb_rf_wnum = Output(UInt(5.W))
    val debug0_wb_rf_wdata = Output(UInt(32.W))
    val debug0_wb_inst = Output(UInt(32.W))
  })
  val core = Module(new Core)
  core.io.clk := io.aclk
  core.io.resetn := io.aresetn
  core.io.resetVector := io.resetVector
  core.io.intrpt := io.intrpt
  io.arid := core.io.arid
  io.araddr := core.io.araddr
  io.arlen := core.io.arlen
  io.arsize := core.io.arsize
  io.arburst := core.io.arburst
  io.arlock := core.io.arlock
  io.arcache := core.io.arcache
  io.arprot := core.io.arprot
  io.arvalid := core.io.arvalid
  core.io.arready := io.arready
  core.io.rid := io.rid
  core.io.rdata := io.rdata
  core.io.rresp := io.rresp
  core.io.rlast := io.rlast
  core.io.rvalid := io.rvalid
  io.rready := core.io.rready
  io.awid := core.io.awid
  io.awaddr := core.io.awaddr
  io.awlen := core.io.awlen
  io.awsize := core.io.awsize
  io.awburst := core.io.awburst
  io.awlock := core.io.awlock
  io.awcache := core.io.awcache
  io.awprot := core.io.awprot
  io.awvalid := core.io.awvalid
  core.io.awready := io.awready
  io.wid := core.io.wid
  io.wdata := core.io.wdata
  io.wstrb := core.io.wstrb
  io.wlast := core.io.wlast
  io.wvalid := core.io.wvalid
  core.io.wready := io.wready
  core.io.bid := io.bid
  core.io.bresp := io.bresp
  core.io.bvalid := io.bvalid
  io.bready := core.io.bready
  io.fatalMemoryError := core.io.fatalMemoryError
  io.ws_valid := 0.U
  io.rf_rdata := 0.U
  io.debug0_wb_pc := 0.U
  io.debug0_wb_rf_wen := 0.U
  io.debug0_wb_rf_wnum := 0.U
  io.debug0_wb_rf_wdata := 0.U
  io.debug0_wb_inst := 0.U
}
