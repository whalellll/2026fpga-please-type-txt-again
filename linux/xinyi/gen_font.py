"""Rebuild only the additional Xinyi UI glyphs; original GUI fonts stay intact.

Use the recorded receipt interpreter with --deps pointing to an isolated Pillow
and fontTools wheel extraction. First creation accepts the installed Noto Sans
SC variable font. Later --check uses the committed renamed static subset.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

DIRECTORY = Path(__file__).resolve().parent
FONTS = DIRECTORY / "fonts"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--deps", type=Path)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.deps:
        sys.path.insert(0, str(args.deps.resolve()))
    import PIL
    from PIL import Image, ImageDraw, ImageFont, features
    import fontTools
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont
    from fontTools import subset

    chars = sorted({c for name in ("xinyi_fb.c", "xinyi_product.c", "xinyi_host.c", "xinyi_home_r13.h")
                    for c in (DIRECTORY/name).read_text(encoding="utf-8")
                    if ord(c) >= 128 and c not in "·→×≥–"})
    # Fixed runtime.c fatal message must stay legible even though its owner
    # builds the board integration separately from this product renderer.
    chars = sorted(set(chars) | set("·→×≥–前中后左右上下进退平一二三四五六七八九十帅将仕士相象马车炮兵卒帥將馬車俥傌砲安全停止未完成，请联系工作人员"))
    font_path = FONTS / "XinyiProductSans.ttf"
    if args.source:
        assert not args.check
        FONTS.mkdir(parents=True, exist_ok=True)
        font = TTFont(args.source, recalcTimestamp=False)
        copyright_text = font["name"].getDebugName(0)
        assert all(ord(c) in font.getBestCmap() for c in chars)
        instantiateVariableFont(font, {"wght": 500}, inplace=True)
        options = subset.Options()
        options.recalc_timestamp = False
        options.name_IDs = ["*"]
        cutter = subset.Subsetter(options=options)
        cutter.populate(text="".join(chars))
        cutter.subset(font)
        names = {1:"Xinyi Product Sans", 2:"Medium", 3:"XQ;XinyiProductSans-Medium",
                 4:"Xinyi Product Sans Medium", 6:"XinyiProductSans-Medium",
                 16:"Xinyi Product Sans", 17:"Medium"}
        for record in font["name"].names:
            if record.nameID in names:
                record.string = names[record.nameID].encode(record.getEncoding())
        font.save(font_path, reorderTables=True)
        (FONTS/"source.json").write_text(json.dumps(dict(
            source_filename=args.source.name, source_sha256=sha(args.source.read_bytes()),
            subset_sha256=sha(font_path.read_bytes()), copyright=copyright_text,
            license="SIL Open Font License 1.1", weight=500,
            fonttools_version=fontTools.__version__), ensure_ascii=False, indent=2)+"\n", encoding="utf-8")

    data = bytearray()
    entries = []
    for size, text in [(24, chars), (32, chars), (64, sorted({c for c in "芯弈一号中国象棋RISC-V对弈平台CoreMark性能测试摄像头调试" if ord(c)>=128}))]:
        font = ImageFont.truetype(str(font_path), size * 4)
        for c in text:
            image = Image.new("L", (size*4, size*4))
            box = font.getbbox(c)
            ImageDraw.Draw(image).text(((size*4-(box[2]-box[0]))//2-box[0],
                                       (size*4-(box[3]-box[1]))//2-box[1]),
                                      c, font=font, fill=255)
            image = image.resize((size, size), Image.Resampling.LANCZOS)
            alpha = [(v*15+127)//255 for v in image.getdata()]
            offset = len(data)
            data.extend((alpha[i]<<4)|alpha[i+1] for i in range(0,len(alpha),2))
            entries.append((ord(c), offset, size, size, size, size))
    lines = ["/* Generated by gen_font.py; Noto Sans SC, SIL OFL 1.1. */",
             "#ifndef XINYI_FONT_H", "#define XINYI_FONT_H", "#include <stdint.h>",
             "typedef struct { uint32_t codepoint, offset; uint16_t size, width, height, advance; } xy_font_glyph;",
             f"#define XY_FONT_GLYPHS {len(entries)}u",
             "static const xy_font_glyph xy_font_glyphs[XY_FONT_GLYPHS] = {"]
    lines.extend("    {%du,%du,%du,%du,%du,%du}," % entry for entry in entries)
    lines += ["};", f"static const uint8_t xy_font_alpha[{len(data)}] = {{"]
    lines.extend("    "+",".join(f"0x{v:02x}" for v in data[i:i+24])+","
                 for i in range(0,len(data),24))
    lines += ["};", "#endif", ""]
    generated = "\n".join(lines).encode()
    receipt = dict(schema=1, characters="".join(chars), glyph_count=len(entries),
                   alpha_bytes=len(data), font_sha256=sha(font_path.read_bytes()),
                   header_sha256=sha(generated), pillow=PIL.__version__,
                   freetype=features.version("freetype2"), fonttools=fontTools.__version__)
    rendered = (json.dumps(receipt, ensure_ascii=False, indent=2)+"\n").encode()
    if args.check:
        assert (DIRECTORY/"xinyi_font.h").read_bytes() == generated
        assert (FONTS/"glyphs.json").read_bytes() == rendered
        print("XINYI_FONT_REBUILD_PASS")
    else:
        (DIRECTORY/"xinyi_font.h").write_bytes(generated)
        (FONTS/"glyphs.json").write_bytes(rendered)
        print(f"XINYI_FONT_GENERATED glyphs={len(entries)} alpha_bytes={len(data)}")


if __name__ == "__main__":
    main()
