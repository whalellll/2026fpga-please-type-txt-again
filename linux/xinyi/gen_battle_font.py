"""Generate only missing r17 glyphs, preserving the complete existing font.

Uses the recorded local OFL font and isolated Pillow/fontTools dependencies.
The original installed font program is never copied into a software package.
"""
from pathlib import Path
import argparse
import hashlib
import io
import json
import re
import sys


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--deps', type=Path, required=True)
    ap.add_argument('--source', type=Path, required=True)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    sys.path.insert(0, str(a.deps.resolve()))
    import PIL
    from PIL import Image, ImageDraw, ImageFont, features
    import fontTools
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont
    here = Path(__file__).resolve().parent
    root = here.parents[1]
    sha = lambda b: hashlib.sha256(b).hexdigest()
    base = (here / 'xinyi_font.h').read_bytes()
    existing = {(int(c), int(s)) for c, _, s, _, _, _ in
        re.findall(rb'\{(\d+)u,(\d+)u,(\d+)u,(\d+)u,(\d+)u,(\d+)u\}', base)}
    names = ['linux/xinyi/xinyi_ui_copy_r20.h', 'linux/xinyi/xinyi_battle_r17.h', 'linux/xinyi/xinyi_battle_metrics_r17.h',
             'linux/xinyi/xinyi_battle_speedups_r17.h', 'linux/xinyi/xinyi_home_metrics_r19.h', 'linux/xinyi/xinyi_home_r13.h', 'linux/xinyi/xinyi_product.c',
             'linux/xinyi_board/runtime.c', 'linux/xinyi_board/voice_bridge.c']
    inputs = {n: (root / n).read_bytes() for n in names}
    chars = sorted({ord(c) for b in inputs.values() for c in b.decode('utf8') if ord(c) >= 128})
    seed = (here / 'xinyi_battle_font_seed_r19.h').read_bytes()
    seed_entries = [tuple(map(int, row)) for row in
        re.findall(rb'\{(\d+)u,(\d+)u,(\d+)u,(\d+)u,(\d+)u,(\d+)u\}', seed)]
    seed_alpha = bytes(int(value, 16) for value in
        re.findall(rb'0x([0-9a-f]{2})', seed[seed.index(b'static const uint8_t'):]))
    seed_glyphs = {(c, size): seed_alpha[offset:offset+width*height//2]
        for c, offset, size, width, height, _ in seed_entries}
    needed = sorted(set((c, size) for size in [24, 32] for c in chars
                        if (c, size) not in existing) | set(seed_glyphs), key=lambda v:(v[1],v[0]))
    data = a.source.read_bytes()
    assert sha(data) == 'd68bafcb48a2707749396aa12bbbd833cb70401f3a9a689fd2902c7e0d295964'
    font = TTFont(io.BytesIO(data), recalcTimestamp=False)
    assert all(c in font.getBestCmap() for c, _ in needed)
    instantiateVariableFont(font, {'wght': 500}, inplace=True)
    memory = io.BytesIO()
    font.save(memory)
    alpha, entries = bytearray(), []
    for c, size in needed:
        if (c, size) in seed_glyphs:
            entries.append((c, len(alpha), size, size, size, size))
            alpha.extend(seed_glyphs[c, size])
            continue
        face = ImageFont.truetype(io.BytesIO(memory.getvalue()), size * 4)
        image = Image.new('L', (size * 4, size * 4))
        box = face.getbbox(chr(c))
        ImageDraw.Draw(image).text(((size*4-(box[2]-box[0]))//2-box[0],
            (size*4-(box[3]-box[1]))//2-box[1]), chr(c), font=face, fill=255)
        image = image.resize((size, size), Image.Resampling.LANCZOS)
        values = [(v * 15 + 127) // 255 for v in image.getdata()]
        entries.append((c, len(alpha), size, size, size, size))
        alpha.extend((values[i] << 4) | values[i+1] for i in range(0, len(values), 2))
    lines = ['/* Generated by gen_battle_font.py; Noto Sans SC / SIL OFL 1.1. */',
        '#ifndef XINYI_BATTLE_FONT_R17_H', '#define XINYI_BATTLE_FONT_R17_H',
        'static const xy_font_glyph xy17_font_glyphs[]={']
    lines.extend('    {%du,%du,%du,%du,%du,%du},' % e for e in entries)
    lines += ['};', f'static const uint8_t xy17_font_alpha[{len(alpha)}]={{']
    lines.extend('    ' + ','.join('0x%02x' % v for v in alpha[i:i+24]) + ','
                 for i in range(0, len(alpha), 24))
    lines += ['};', '#endif', '']
    header = '\n'.join(lines).encode()
    receipt = dict(schema='xinyi-battle-font-r17/1', glyph_count=len(entries),
        glyphs=[dict(codepoint=c, size=s) for c, s in needed], alpha_bytes=len(alpha),
        base_header_sha256=sha(base), base_preserved=True, source_font_sha256=sha(data),
        seed_header_sha256=sha(seed), seed_glyphs_preserved=len(seed_glyphs),
        header_sha256=sha(header), source_sha256={n: sha(b) for n, b in inputs.items()},
        pillow=PIL.__version__, freetype=features.version('freetype2'), fonttools=fontTools.__version__)
    metadata = (json.dumps(receipt, indent=2) + '\n').encode()
    if a.check:
        assert (here / 'xinyi_battle_font_r17.h').read_bytes() == header
        assert (here / 'fonts/battle-r17.json').read_bytes() == metadata
    else:
        (here / 'xinyi_battle_font_r17.h').write_bytes(header)
        (here / 'fonts/battle-r17.json').write_bytes(metadata)
    assert (here / 'xinyi_font.h').read_bytes() == base
    print('R17_SUPPLEMENT_GLYPHS_BASE_PRESERVED_PASS', len(entries))


if __name__ == '__main__':
    main()
