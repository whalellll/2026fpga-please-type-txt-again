#ifndef PF_STAGEB_POSITION_GOLDEN_H
#define PF_STAGEB_POSITION_GOLDEN_H

#include <stdint.h>

/* PFG2: legal-position Stage B acceptance vectors. All fields are little-endian. */
#define PF_STAGEB_POSITION_MAGIC 0x32474650u
#define PF_STAGEB_POSITION_VERSION 0x00010000u
#define PF_STAGEB_POSITION_HEADER_BYTES 160u
#define PF_STAGEB_POSITION_BUCKET_COUNT 16u
#define PF_STAGEB_POSITION_CASES_PER_BUCKET 2u
#define PF_STAGEB_POSITION_CASE_COUNT \
    (PF_STAGEB_POSITION_BUCKET_COUNT * PF_STAGEB_POSITION_CASES_PER_BUCKET)
#define PF_STAGEB_POSITION_FEATURE_COUNT 1024u
#define PF_STAGEB_POSITION_FC0_LANES 32u

#define PF_STAGEB_POSITION_RECORD_META_WORDS 9u
#define PF_STAGEB_POSITION_RECORD_META_BYTES \
    (PF_STAGEB_POSITION_RECORD_META_WORDS * 4u)
#define PF_STAGEB_POSITION_FEATURE_OFFSET PF_STAGEB_POSITION_RECORD_META_BYTES
#define PF_STAGEB_POSITION_FC0_OFFSET \
    (PF_STAGEB_POSITION_FEATURE_OFFSET + PF_STAGEB_POSITION_FEATURE_COUNT)
#define PF_STAGEB_POSITION_RECORD_BYTES \
    (PF_STAGEB_POSITION_FC0_OFFSET + PF_STAGEB_POSITION_FC0_LANES * 4u)
#define PF_STAGEB_POSITION_PAYLOAD_BYTES \
    (PF_STAGEB_POSITION_CASE_COUNT * PF_STAGEB_POSITION_RECORD_BYTES)
#define PF_STAGEB_POSITION_TOTAL_BYTES \
    (PF_STAGEB_POSITION_HEADER_BYTES + PF_STAGEB_POSITION_PAYLOAD_BYTES)

#define PF_STAGEB_POSITION_FLAG_FEATURES 0x00000001u
#define PF_STAGEB_POSITION_FLAG_FC0 0x00000002u
#define PF_STAGEB_POSITION_FLAG_PSQT 0x00000004u
#define PF_STAGEB_POSITION_FLAG_POSITIONAL 0x00000008u
#define PF_STAGEB_POSITION_FLAG_FINAL_EVAL 0x00000010u
#define PF_STAGEB_POSITION_FLAGS \
    (PF_STAGEB_POSITION_FLAG_FEATURES | PF_STAGEB_POSITION_FLAG_FC0 | \
     PF_STAGEB_POSITION_FLAG_PSQT | PF_STAGEB_POSITION_FLAG_POSITIONAL | \
     PF_STAGEB_POSITION_FLAG_FINAL_EVAL)

/* Header offsets. */
#define PF_STAGEB_POSITION_H_MAGIC 0u
#define PF_STAGEB_POSITION_H_VERSION 4u
#define PF_STAGEB_POSITION_H_HEADER_BYTES 8u
#define PF_STAGEB_POSITION_H_TOTAL_BYTES 12u
#define PF_STAGEB_POSITION_H_CASE_COUNT 16u
#define PF_STAGEB_POSITION_H_BUCKET_COUNT 20u
#define PF_STAGEB_POSITION_H_FEATURE_COUNT 24u
#define PF_STAGEB_POSITION_H_FC0_LANES 28u
#define PF_STAGEB_POSITION_H_RECORD_BYTES 32u
#define PF_STAGEB_POSITION_H_PAYLOAD_CRC32 36u
#define PF_STAGEB_POSITION_H_CORPUS_CRC32 40u
#define PF_STAGEB_POSITION_H_MLPS_CRC32 44u
#define PF_STAGEB_POSITION_H_PFSB_CRC32 48u
#define PF_STAGEB_POSITION_H_FLAGS 52u
#define PF_STAGEB_POSITION_H_SOURCE_SHA256 56u
#define PF_STAGEB_POSITION_H_DECODED_SHA256 88u

/* Record word offsets. */
#define PF_STAGEB_POSITION_R_BUCKET 0u
#define PF_STAGEB_POSITION_R_SIDE_TO_MOVE 4u
#define PF_STAGEB_POSITION_R_FEN_CRC32 8u
#define PF_STAGEB_POSITION_R_PSQT_RAW 12u
#define PF_STAGEB_POSITION_R_POSITIONAL_RAW 16u
#define PF_STAGEB_POSITION_R_PSQT 20u
#define PF_STAGEB_POSITION_R_POSITIONAL 24u
#define PF_STAGEB_POSITION_R_NNUE 28u
#define PF_STAGEB_POSITION_R_FINAL_EVAL 32u

static inline uint32_t pf_stageb_position_record_offset(uint32_t case_index) {
    return PF_STAGEB_POSITION_HEADER_BYTES +
           case_index * PF_STAGEB_POSITION_RECORD_BYTES;
}

#endif
