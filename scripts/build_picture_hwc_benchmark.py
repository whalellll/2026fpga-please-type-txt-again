"""Prepare the upstream57s fixed-input experiment; build/mock only, no board."""
from pathlib import Path
import argparse,hashlib,json,re,shlex,subprocess,zipfile
from picture_workspace import ROOT,workspace_path,wsl_path

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--reproduced',type=Path,required=True)
    a=p.parse_args();assert a.output.absolute().is_relative_to(ROOT/'build')
    out=workspace_path(a.output);out.mkdir(parents=True,exist_ok=False)
    sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    expected={'detector.xqi':'d72d039041b41310f037344772eb75ce895ec6fe678bbb31ed547a7ad7453942',
              'detector.hwc8':'102ed005330661fa1576afa5b6ceb60b6407e7b9c1475252fb183cd176c0f27a'}
    for name,digest in expected.items():
        src=workspace_path(a.reproduced/name);assert sha(src)==digest;(out/name).write_bytes(src.read_bytes())
    sources=['linux/picture_new/hwc_fast/matched_bench.c','linux/picture_new/hwc_fast/integer_hwc.c',
             'linux/picture_new/vision32_backend.c','linux/picture_new/vision32_layer.c',
             'linux/picture_new/graph_profile.c','sw/bootloader/crc32_fast.c']
    mock='linux/picture_new/hwc_fast/tests/picture_new_graph_mock.c'
    includes=['linux/picture_new/hwc_fast','linux/picture_new','linux/mac_accel','linux/vision',
              'sw/bootloader','artifacts/vision-model-20261020-adapter/runtime']
    files=set(sources+[mock,'scripts/build_picture_hwc_benchmark.py','linux/picture_new/hwc_fast/integer_bench.c',
        'linux/picture_new/hwc_fast/tests/test_bench_control.c','linux/picture_new/vision32_locality.c',
        'linux/picture_new/vision32_exact.c','linux/picture_new/upstream/adapter/runtime/xq_int8_layer.c',
        'linux/picture_new/upstream/adapter/runtime/xq_int8_layer.h'])
    for d in includes:files.update(p.relative_to(ROOT).as_posix() for p in (ROOT/d).glob('*.h'))
    before={n:sha(ROOT/n) for n in sorted(files)}
    result=dict(status='FAILED_PRESERVED',hardware_used=False,source_sha256=before,runs=[])
    def run(label,args,seconds=120):
        with (out/(label+'.log')).open('xb') as f:r=subprocess.run(['wsl.exe','-d','Ubuntu-22.04','--','sh','-c',
            'ulimit -c 0\nexec timeout --kill-after=5 '+str(seconds)+' '+shlex.join(args)],stdout=f,stderr=subprocess.STDOUT,timeout=seconds+20)
        result['runs'].append(dict(name=label,exit=r.returncode));assert r.returncode==0,(label,(out/(label+'.log')).read_text(errors='replace')[-1800:])
    try:
        flags=['-std=c11','-O2','-Wall','-Wextra','-Werror','-Wno-misleading-indentation','-ffp-contract=off','-ffunction-sections','-fdata-sections']
        for target in ['hostmock','rv32']:
            cc='gcc' if target=='hostmock' else '/opt/toolchain/bin/riscv32-linux-musl-gcc'
            extra=['-static','-march=rv32ima','-mabi=ilp32','-mstrict-align'] if target=='rv32' else []
            current=sources+([mock] if target=='hostmock' else [])
            link=['-Wl,--wrap=open,--wrap=close,--wrap=mmap,--wrap=munmap,--wrap=ioctl'] if target=='hostmock' else []
            run(target+'-build',[cc,*flags,*extra,*['-I'+wsl_path(ROOT/d) for d in includes],
                *[wsl_path(ROOT/n) for n in current],*link,'-Wl,--gc-sections','-lm','-o',wsl_path(out/('integer-detector-'+target))])
            control=out/(target+'-control')
            control_sources=[*sources[1:],'linux/picture_new/hwc_fast/tests/test_bench_control.c',mock]
            run(target+'-control-build',[cc,*flags,*extra,*['-I'+wsl_path(ROOT/d) for d in includes],
                *[wsl_path(ROOT/n) for n in control_sources],'-Wl,--wrap=open,--wrap=close,--wrap=mmap,--wrap=munmap,--wrap=ioctl',
                '-Wl,--gc-sections','-lm','-o',wsl_path(control)])
            run(target+'-control-run',[*(['qemu-riscv32'] if target=='rv32' else []),wsl_path(control)])
            assert 'MATCHED_BENCH_SIGINT_TERM_DRIVER_CALLBACK_NO_JOB_PASS_NOT_BOARD' in (out/(target+'-control-run.log')).read_text()
        output=out/'hostmock-output.f32'
        run('hostmock-fixed-run',[wsl_path(out/'integer-detector-hostmock'),wsl_path(out/'detector.xqi'),wsl_path(out/'detector.hwc8'),'1',wsl_path(output)],240)
        log=(out/'hostmock-fixed-run.log').read_text();assert 'output_crc=97265de4' in log and 'jobs=166' in log
        # Expected head bytes were independently generated by the frozen CPU
        # runtime during the preceding integration check; never a live image.
        reference=workspace_path(ROOT/'build/picture-e42-20261025/hwc-rgb-profile-r01/fixed-reference.f32')
        assert output.read_bytes()==reference.read_bytes()
        b=(out/'integer-detector-rv32').read_bytes()
        assert b[:6]==b'\x7fELF\x01\x01' and int.from_bytes(b[18:20],'little')==243 and not int.from_bytes(b[36:40],'little')
        assert all(sha(ROOT/n)==h for n,h in before.items())
        doc='''# 与上游57秒记录对齐的固定输入测试（待上板）

这里只含已冻结的合成输入，不含照片或数据集。程序绑定同一XQI/HWC8和166作业。
RV32程序访问真实驱动；本次只构建它。hostmock已执行完整输出对照，时间不能算板速。

恢复板测、核对e42/内核/空闲与运行身份后，才可在独立RAM目录运行：

```
./integer-detector-rv32 detector.xqi detector.hwc8 1 output.f32
```

先只运行一次，主机收集器总上限240秒。SIGINT/TERM已接入驱动取消回调，仍须确认
abort/drain、进程退出及五BUSY；单凭退出或超时不能宣称安全释放。
INTEGER_TIMING.graph_us + output_export_us才与上游57.180712秒比较。读取、CRC、
相机、GUI、NMS、棋盘定位、棋子分类与几何校正均不在此数字内。完整三头文件保留。
它不代替整盘<=60秒验收。禁止把当前实景133秒阶段直接除以上游57秒称作倍率。
硬件忙时属于graph_us，不可再次相加。下一步按INTEGER_STAGES的打包、ioctl、
输出、非卷积拆分，区分驱动/编译配置差距和产品多出的处理。
'''
        (out/'README.zh.md').write_text(doc,encoding='utf-8')
        selected=['integer-detector-rv32','detector.xqi','detector.hwc8','README.zh.md']
        (out/'SHA256SUMS').write_text(''.join(sha(out/n)+'  '+n+'\n' for n in selected))
        with zipfile.ZipFile(out/'matched-benchmark.zip','x',compression=zipfile.ZIP_DEFLATED) as z:
            for n in [*selected,'SHA256SUMS']:z.write(out/n,n)
        result.update(status='MATCHED_UPSTREAM_FIXED_INPUT_BENCHMARK_BUILT_HOSTMOCK_FULL_OUTPUT_PASS_NOT_BOARD',
            inputs_sha256=expected,jobs=166,full_output_equal_frozen_cpu=True,rv32_built_not_run=True,
            signal_cancel_callback_host_rv32=True,
            board_result=None,source_stable=True,package_sha256=sha(out/'matched-benchmark.zip'))
    finally:(out/'result.json').write_text(json.dumps(result,indent=2)+'\n')
    print(result['status'])
if __name__=='__main__':main()
