"""Full independent regression and GUI rebuild from the sealed extracted bytes.

Only the disposable extraction is used. Native metadata regenerated by tests is
recorded, and restored from the unchanged ZIP after exact binary equality checks.
The external receipt binds this work to the ZIP; final media remains separate.
"""
from pathlib import Path
from datetime import datetime,timezone
from zipfile import ZipFile
import argparse,hashlib,json,os,re,shutil,subprocess,sys
from workspace_paths import workspace_path,wsl_path
from verify_main75_delivery import verify
from verify_main75_release import GUI
from verify_board_release import need,sha,read,safe

def validate_rebuilt_artifact_manifest(root, sealed_bytes, metadata, original):
    """Permit only reordering and hashes of independently verified build JSON."""
    def parse(data):
        rows={};seen=set()
        for line in data.decode('ascii').splitlines():
            m=re.fullmatch(r'([0-9a-f]{64})  ([A-Za-z0-9_.-]+)',line)
            need(m is not None and m[2] not in {'.','..'},'Unsafe artifact manifest row')
            name=m[2];need(name.casefold() not in seen,'Duplicate artifact manifest row')
            seen.add(name.casefold());rows[name]=m[1]
        need(bool(rows),'Empty artifact manifest');return rows
    old=parse(sealed_bytes);new=parse((root/'artifacts/SHA256SUMS.txt').read_bytes())
    need(old.keys()==new.keys(),'Rebuild changed artifact manifest inventory')
    for name,h in old.items():
        key='artifacts/'+name
        need(original.get(key)==h,'Sealed artifact manifest differs from sealed file '+name)
        need(sha(safe(root,key))==new[name],'Rebuilt artifact manifest hash differs '+name)
        if new[name]!=h:
            need(name.endswith('.build.json') and metadata.get(key)==new[name],
                 'Rebuild changed protected artifact '+name)

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    for name in ['root','zip','output']:ap.add_argument('--'+name,type=Path,required=True)
    a=ap.parse_args();root,zipfile,out=map(workspace_path,[a.root,a.zip,a.output])
    need(not out.exists(),'Preserve previous verification attempt');out.mkdir(parents=True)
    tmp=out/'tmp';tmp.mkdir()
    record=dict(status='RUNNING_ZIP_BOUND_INDEPENDENT_REGRESSION',owner_pid=os.getpid(),
        started_utc=datetime.now(timezone.utc).isoformat(),zip_sha256=sha(zipfile),root=str(root),commands=[],formal_delivery_complete=False)
    def save():(out/'result.json').write_text(json.dumps(record,indent=2)+'\n')
    save();env=dict(os.environ,TEMP=str(tmp),TMP=str(tmp),TMPDIR=str(tmp))
    def run(name,cmd,timeout):
        log=out/(name+'.log')
        with log.open('xb') as f:p=subprocess.run(cmd,cwd=root,env=env,stdout=f,stderr=subprocess.STDOUT,timeout=timeout)
        record['commands'].append(dict(name=name,argv=cmd,exit=p.returncode,log_sha256=sha(log)));save()
        need(p.returncode==0,'Extracted check failed '+name);return log
    try:
        verify(root,'G:/fpga/workspace/tools/msys64/mingw64/bin/gcc.exe')
        sealed=read(root/'MAIN75_DELIVERY.json');original=sealed['files_sha256']
        run('skills',[sys.executable,'-B',str(root/'skills/manage.py'),'verify-delivery','--package',str(root)],120)
        run('index',[sys.executable,'-B',str(root/'scripts/update_project_index.py'),'--project-root',str(root),'--check'],120)
        # Matching GCC/Verilator/Icarus installations are project dependencies;
        # all source, fixtures, model data and outputs come from this extraction.
        log=run('full-soc',['powershell.exe','-NoProfile','-ExecutionPolicy','Bypass','-File',str(root/'scripts/run_all_tests.ps1'),
            '-IcarusBin','G:/fpga/workspace/tools/msys64/ucrt64/bin','-MsysRoot','G:/fpga/workspace/tools/msys64',
            '-ToolchainBin','G:/fpga/workspace/tools/riscv32-gcc16/bin','-PythonPath',sys.executable,
            '-HostGccPath','G:/fpga/workspace/tools/msys64/mingw64/bin/gcc.exe','-PdsRoot','G:/fpga/PDS_2022.2-SP6.4',
            '-PllWslDistro','pikafish-verify','-MacPeWslDistro','pikafish-verify',
            '-PolicyFixtureRoot',str(root/'prebuilt/cpu80-policy-fixture')],7200)
        need(b'SOC_ALL_TESTS_PASS' in log.read_bytes(),'Full regression completion missing')
        run('gui-runtime',[sys.executable,'-B',str(root/'scripts/check_xinyi_runtime.py'),
            '--output',str(root/'build/package-gui-runtime'),'--distribution','pikafish-verify'],600)
        run('clock-boot',[sys.executable,'-B',str(root/'scripts/test_main75_boot_sync.py'),
            '--source-root',str(root),'--output',str(root/'build/package-clock-boot')],600)
        gui=root/'build/package-gui-rebuild'
        run('gui-build',['wsl.exe','-d','pikafish-verify','--','env','TMPDIR='+wsl_path(tmp),
            'TMP='+wsl_path(tmp),'TEMP='+wsl_path(tmp),'XINYI_CPU_HZ=75000000',
            'sh',wsl_path(root/'linux/xinyi_board/build.sh'),wsl_path(gui)],600)
        run('gui-strip',['wsl.exe','-d','pikafish-verify','--','/opt/toolchain/bin/riscv32-linux-musl-strip',
            '--strip-unneeded','-o',wsl_path(gui/'xinyi-one-stripped'),wsl_path(gui/'xinyi-one')],120)
        need(sha(gui/'xinyi-one-stripped')==GUI,'Independently rebuilt GUI ELF differs')
        changed={n:sha(safe(root,n)) for n,h in original.items() if sha(safe(root,n))!=h}
        # Rebuilt firmware/ROM bytes must be identical. Only build-metadata JSON
        # can be restored; a changed source, model, bitstream or binary is failure.
        need(all(n=='artifacts/SHA256SUMS.txt' or (n.startswith('artifacts/') and n.endswith('.build.json')) for n in changed),'Regression changed protected source/runtime bytes: '+str(changed))
        record['regenerated_metadata_sha256']=changed
        with ZipFile(zipfile) as archive:
            if 'artifacts/SHA256SUMS.txt' in changed:
                metadata={n:h for n,h in changed.items() if n.endswith('.build.json')}
                validate_rebuilt_artifact_manifest(root,archive.read('SOC/artifacts/SHA256SUMS.txt'),metadata,original)
            for name in changed:
                data=archive.read('SOC/'+name);need(hashlib.sha256(data).hexdigest()==original[name],'ZIP metadata mismatch')
                (root/name).write_bytes(data)
        need(sha(zipfile)==record['zip_sha256'],'ZIP changed during verification')
        record['independent_content_after_regression']=verify(root,'G:/fpga/workspace/tools/msys64/mingw64/bin/gcc.exe')
        record.update(status='ZIP_BOUND_MAIN75_INDEPENDENT_FULL_REGRESSION_AND_EXACT_GUI_REBUILD_PASS_FINAL_MEDIA_PENDING',
            full_regression=True,gui_rebuilt_sha256=GUI,final_media=False)
    except Exception as error:record.update(status='FAILED_PRESERVED',error=repr(error));raise
    finally:record['completed_utc']=datetime.now(timezone.utc).isoformat();save()
    print(record['status'])

if __name__=='__main__':main()
