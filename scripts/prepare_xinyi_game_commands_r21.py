"""Pack exact scalar game pixels into sequential fill/literal commands."""
from pathlib import Path
import argparse,hashlib,json,struct
from picture_workspace import ROOT,workspace_path

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--frames',type=Path,required=True);ap.add_argument('--output',type=Path,required=True)
    a=ap.parse_args();frames=workspace_path(a.frames);out=workspace_path(a.output);out.mkdir(exist_ok=False)
    lines=['/* Exact scalar game pixels; generated by prepare_xinyi_game_commands_r21.py. */',
           '#ifndef XINYI_GAME_COMMANDS_R21_H','#define XINYI_GAME_COMMANDS_R21_H']
    rows=[]
    for part in range(4):
        mode=max(0,part-1)
        source=frames/f'game-{mode}.rgb565';raw=source.read_bytes();assert len(raw)==4147200
        pixels=struct.unpack('<1036800I',raw);commands=[];literal=[];start=0
        def flush():
            if literal:commands.extend([start,len(literal),*literal]);literal.clear()
        for row in range(1080):
            at=row*960+(479 if part else 0);limit=row*960+(960 if part else 479)
            while at<limit:
                end=at+1
                while end<limit and pixels[end]==pixels[at]:end+=1
                count=end-at
                if count>=4:
                    flush();commands.extend([at,0x80000000|count,pixels[at]])
                else:
                    if literal and len(literal)+count>1024:flush()
                    if not literal:start=at
                    literal.extend(pixels[at:end])
                at=end
            flush()
        flush();commands.append(0xffffffff)
        lines.append(f'static const uint32_t xy21_commands_{part}[]={{')
        lines.extend(','.join(f'0x{x:08x}u' for x in commands[i:i+8])+',' for i in range(0,len(commands),8))
        lines.append('};');rows.append(dict(part=part,mode=mode,words=len(commands),bytes=len(commands)*4,frame_sha256=hashlib.sha256(raw).hexdigest()))
    lines+=['static const uint32_t *const xy21_commands[4]={xy21_commands_0,xy21_commands_1,xy21_commands_2,xy21_commands_3};','#endif','']
    header=ROOT/'linux/xinyi/xinyi_game_commands_r21.h';header.write_bytes('\n'.join(lines).encode())
    (out/'result.json').write_text(json.dumps(dict(status='R21_EXACT_GAME_COMMANDS_NOT_BOARD',frames=str(frames),pages=rows,
        header_sha256=hashlib.sha256(header.read_bytes()).hexdigest(),producer_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()),indent=2)+'\n')
    print(sum(x['bytes'] for x in rows))

if __name__=='__main__':main()
