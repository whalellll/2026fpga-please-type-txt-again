"""Generate CPU60 static page runs using the actual renderer, offline only."""
from pathlib import Path
import argparse, hashlib, json, shlex, struct, subprocess
from picture_workspace import ROOT, workspace_path, wsl_path


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output',required=True,type=Path)
    a=ap.parse_args();out=workspace_path(a.output);out.mkdir(parents=True,exist_ok=False)
    dirs=['linux/xinyi_board','linux/xinyi','linux/pikafish','linux/pikafish/include',
          'linux/vision','linux/voice','linux/voice_ctc','linux/voice_speech',
          'linux/mac_accel','linux/picture_new','sw/xiangqi','sw/bootloader',
          'artifacts/vision-model-20261020-adapter/runtime']
    names=['linux/xinyi/page_template_export.c','linux/xinyi/xinyi_product.c',
           'linux/voice/xqvoice_protocol.c','sw/xiangqi/xiangqi_search.c',
           'sw/xiangqi/xiangqi_pikafish_link.c']
    sources=set(names+['linux/xinyi/xinyi_fb.c','linux/pikafish/xiangqi_fb_gui_1080.c',
                       'scripts/prepare_xinyi_page_templates.py'])
    for directory in dirs:
        sources.update(p.relative_to(ROOT).as_posix() for p in (ROOT/directory).glob('*.h')
                       if p.name!='xinyi_page_templates.h')
    sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    before={name:sha(ROOT/name) for name in sorted(sources)}
    exe=out/'export'
    argv=['cc','-std=c11','-O2','-Wall','-Wextra','-Werror','-Wno-misleading-indentation',
          '-D_POSIX_C_SOURCE=200809L','-DXINYI_CPU_HZ=60000000','-DXINYI_HOME_R13=1',
          '-DXINYI_HOME_R15=1','-DXINYI_GUI_DOUBLE_BUFFER=1','-DXINYI_UI_FEEDBACK=1',
          '-DXINYI_SCALAR_GLYPH_ORACLE','-DVIDEO_FB_LINUX_MMAP',
          '-include',wsl_path(ROOT/'linux/pikafish/gui1080_config.h'),
          *['-I'+wsl_path(ROOT/d) for d in dirs],*[wsl_path(ROOT/n) for n in names],
          '-lm','-o',wsl_path(exe)]
    for label,command in [('build',argv),('export',[wsl_path(exe),wsl_path(out)])]:
        q=subprocess.run(['wsl.exe','-d','Ubuntu-22.04','--','sh','-c',
                          'ulimit -c 0\nexec timeout 120 '+shlex.join(command)],
                         capture_output=True,timeout=135)
        (out/(label+'.log')).write_bytes(q.stdout+q.stderr);assert q.returncode==0,(label,q.stderr[-1500:])
    lines=['/* CPU60 offline exact page pixels; generated by prepare_xinyi_page_templates.py. */',
           '#ifndef XINYI_PAGE_TEMPLATES_H','#define XINYI_PAGE_TEMPLATES_H',
           '#include <stdint.h>','typedef struct {uint32_t count,value;} xy15_run;']
    records=[]
    for page in range(4):
        path=out/f'page-{page}.rgb565';data=path.read_bytes();words=struct.unpack('<1036800I',data)
        runs=[];start=0
        while start<len(words):
            end=start+1
            while end<len(words) and words[end]==words[start]:end+=1
            runs.append((end-start,words[start]));start=end
        lines.append(f'static const xy15_run xy15_page_{page}[]={{')
        lines.extend(','.join('{%du,0x%08xu}'%v for v in runs[i:i+4])+',' for i in range(0,len(runs),4))
        lines.append('};');records.append(dict(page=page,runs=len(runs),sha256=sha(path)))
    lines+=['static const xy15_run *const xy15_pages[4]={xy15_page_0,xy15_page_1,xy15_page_2,xy15_page_3};',
            '#endif','']
    header='\n'.join(lines).encode();assert before=={n:sha(ROOT/n) for n in before}
    (ROOT/'linux/xinyi/xinyi_page_templates.h').write_bytes(header)
    meta=dict(status='GENERATED_NOT_BOARD',cpu_hz=60000000,source_sha256=before,pages=records,
              header_sha256=hashlib.sha256(header).hexdigest(),rom_bytes=sum(v['runs'] for v in records)*8)
    (out/'result.json').write_text(json.dumps(meta,indent=2)+'\n')
    print('EXACT_PAGE_TEMPLATE_EXPORT_PASS',meta['rom_bytes'])


if __name__=='__main__':main()
