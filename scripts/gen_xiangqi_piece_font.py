"""Generate native-size, 4-bit coverage chess glyphs; no font engine on the board."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import PIL
from PIL import Image, ImageDraw, ImageFont, features

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / 'linux/pikafish/fonts'
FONT = FONT_DIR / 'XiangqiPieceSerif.ttf'
HEADER = ROOT / 'linux/pikafish/xiangqi_piece_font_aa.h'
MANIFEST = FONT_DIR / 'piece-font.json'
CHARACTERS = '帅将仕士相象马车炮兵卒'
SIZE = 48
SUPERSAMPLE = 4


def sha(data):
    return hashlib.sha256(data).hexdigest()


def make_subset(source, weight):
    from fontTools import subset, __version__
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont

    original = source.read_bytes()
    font = TTFont(source, recalcTimestamp=False)
    copyright_text = font['name'].getDebugName(0)
    family = font['name'].getDebugName(1)
    if 'fvar' in font:
        instantiateVariableFont(font, {'wght': weight}, inplace=True)
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.recalc_timestamp = False
    small = subset.Subsetter(options=options)
    small.populate(text=CHARACTERS)
    small.subset(font)
    names = {1:'Xiangqi Piece Serif', 2:'Medium', 3:'XQ;XiangqiPieceSerif-Medium',
             4:'Xiangqi Piece Serif Medium', 6:'XiangqiPieceSerif-Medium',
             16:'Xiangqi Piece Serif', 17:'Medium'}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    font.save(FONT, reorderTables=True)
    provenance = {'source_filename': source.name, 'source_family': family,
                  'source_sha256': sha(original), 'copyright': copyright_text,
                  'weight': weight, 'subset_family': 'Xiangqi Piece Serif',
                  'fonttools_version': __version__, 'subset_sha256': sha(FONT.read_bytes()),
                  'license': 'SIL Open Font License 1.1',
                  'license_url': 'https://raw.githubusercontent.com/notofonts/noto-cjk/main/Serif/LICENSE'}
    (FONT_DIR/'source.json').write_bytes((json.dumps(provenance, ensure_ascii=False, indent=2)+'\n').encode('utf-8'))


def rasterize():
    font = ImageFont.truetype(str(FONT), 44*SUPERSAMPLE)
    glyphs = []
    stats = []
    for character in CHARACTERS:
        box = font.getbbox(character)
        assert box and box[2] > box[0] and box[3] > box[1]
        mask = Image.new('L', (box[2]-box[0],box[3]-box[1]))
        ImageDraw.Draw(mask).text((-box[0],-box[1]),character,font=font,fill=255)
        # Preserve the outline and aspect ratio. Keep all coverage inside the
        # flat piece face: the renderer can blend against its known background.
        scale = min(1.0, 40*SUPERSAMPLE/max(mask.size))
        while True:
            fitted = mask.resize((max(1,round(mask.width*scale)),max(1,round(mask.height*scale))),Image.Resampling.LANCZOS)
            canvas = Image.new('L',(SIZE*SUPERSAMPLE,SIZE*SUPERSAMPLE))
            canvas.paste(fitted, ((canvas.width-fitted.width)//2,(canvas.height-fitted.height)//2))
            canvas = canvas.resize((SIZE,SIZE),Image.Resampling.LANCZOS)
            alpha = [(value*15+127)//255 for value in canvas.getdata()]
            radius2 = max((i%SIZE-24)**2+(i//SIZE-24)**2 for i,a in enumerate(alpha) if a)
            if radius2 <= 27*27:
                break
            scale *= 0.97
        packed = bytes((alpha[i]<<4)|alpha[i+1] for i in range(0,len(alpha),2))
        levels = sorted(set(alpha))
        assert len(packed)==SIZE*SIZE//2 and len(levels)>=12
        glyphs.append(packed)
        stats.append({'character': character, 'coverage_levels': levels,
                      'intermediate_pixels':sum(0<a<15 for a in alpha),
                      'nonzero_pixels':sum(a>0 for a in alpha),
                      'ink_radius_squared':radius2, 'sha256':sha(packed)})
    lines=['/* Generated by scripts/gen_xiangqi_piece_font.py; do not hand edit.',
           ' * Native 48x48 vector raster, 16 coverage levels, two pixels per byte.',
           ' * Derived from Noto Serif SC; font license/provenance in fonts/. */',
           '#ifndef XIANGQI_PIECE_FONT_AA_H','#define XIANGQI_PIECE_FONT_AA_H','',
           '#include <stdint.h>','#define XQ_PIECE_GLYPH_SIZE 48',
           '#define XQ_PIECE_GLYPH_COUNT 11','#define XQ_PIECE_GLYPH_BYTES 1152','',
           'static const uint8_t xq_piece_alpha4[XQ_PIECE_GLYPH_COUNT][XQ_PIECE_GLYPH_BYTES] = {']
    for character, data in zip(CHARACTERS,glyphs):
        lines.append('    { /* '+character+' */')
        for i in range(0,len(data),24):
            lines.append('        '+','.join('0x%02x'%v for v in data[i:i+24])+',')
        lines.append('    },')
    lines+=['};','','#endif','']
    header='\n'.join(lines).encode('utf-8')
    manifest={'schema':1,'characters':CHARACTERS,'size':SIZE,'coverage_bits':4,
              'supersample':SUPERSAMPLE,'font_pixel_size':44,
              'subset_sha256':sha(FONT.read_bytes()),'header_sha256':sha(header),
              'alpha_bytes':sum(map(len,glyphs)), 'pillow_version':PIL.__version__,
              'freetype_version':features.version('freetype2'), 'glyphs':stats}
    return header,(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode('utf-8')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-font',type=Path,help='Create a renamed, static 11-character subset first.')
    parser.add_argument('--weight',type=int,default=550)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    if args.source_font:
        if args.check: parser.error('--source-font and --check cannot be combined')
        make_subset(args.source_font,args.weight)
    header,manifest=rasterize()
    if args.check:
        assert HEADER.read_bytes()==header,'Generated glyph header differs'
        assert MANIFEST.read_bytes()==manifest,'Glyph metadata differs'
        print('PIECE_FONT_REGENERATION_PASS glyphs=11 size=48 alpha=4bit data=12672bytes')
    else:
        HEADER.write_bytes(header)
        MANIFEST.write_bytes(manifest)
        print('PIECE_FONT_GENERATED glyphs=11 size=48 alpha=4bit data=12672bytes')


if __name__=='__main__':
    main()
