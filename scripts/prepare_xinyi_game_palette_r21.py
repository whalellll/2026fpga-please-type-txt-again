"""Exact palette/RLE game pixels: 16-bit short runs, bounded long-run escapes."""
from pathlib import Path
import argparse,hashlib,json,struct
from picture_workspace import ROOT,workspace_path

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--frames',type=Path,required=True);ap.add_argument('--output',type=Path,required=True)
    a=ap.parse_args();frames=workspace_path(a.frames);out=workspace_path(a.output);out.mkdir(exist_ok=False)
    lines=['/* Exact scalar renderer pixels; generated by prepare_xinyi_game_palette_r21.py. */','#ifndef XINYI_GAME_PALETTE_R21_H','#define XINYI_GAME_PALETTE_R21_H'];rows=[]
    for part in range(4):
        mode=max(0,part-1);raw=(frames/f'game-{mode}.rgb565').read_bytes();assert len(raw)==4147200
        pixels=struct.unpack('<1036800I',raw);palette=[];indices={};codes=[]
        for row in range(1080):
            at=row*960+(479 if part else 0);limit=row*960+(960 if part else 479)
            while at<limit:
                end=at+1
                while end<limit and pixels[end]==pixels[at]:end+=1
                count=end-at;value=pixels[at]
                if value not in indices:indices[value]=len(palette);palette.append(value)
                index=indices[value];assert index<4096 and 0<count<65536
                codes.append(index|((count if count<16 else 0)<<12))
                if count>=16:codes.append(count)
                at=end
        lines.append(f'static const uint32_t xy21_palette_{part}[]={{')
        lines.extend(','.join(f'0x{x:08x}u' for x in palette[i:i+8])+',' for i in range(0,len(palette),8));lines.append('};')
        lines.append(f'static const uint16_t xy21_codes_{part}[]={{')
        lines.extend(','.join(f'0x{x:04x}u' for x in codes[i:i+12])+',' for i in range(0,len(codes),12));lines.append('};')
        rows.append(dict(part=part,palette_entries=len(palette),code_halfwords=len(codes),bytes=len(palette)*4+len(codes)*2,frame_sha256=hashlib.sha256(raw).hexdigest()))
    lines+=['static const uint32_t *const xy21_palettes[4]={xy21_palette_0,xy21_palette_1,xy21_palette_2,xy21_palette_3};','static const uint16_t *const xy21_codes[4]={xy21_codes_0,xy21_codes_1,xy21_codes_2,xy21_codes_3};','#endif','']
    header=ROOT/'linux/xinyi/xinyi_game_palette_r21.h';header.write_bytes('\n'.join(lines).encode())
    (out/'result.json').write_text(json.dumps(dict(status='R21_EXACT_GAME_PALETTE_NOT_BOARD',pages=rows,header_sha256=hashlib.sha256(header.read_bytes()).hexdigest(),producer_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()),indent=2)+'\n');print(sum(x['bytes'] for x in rows))

if __name__=='__main__':main()
